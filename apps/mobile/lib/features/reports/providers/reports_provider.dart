  }
}

final reportGenerationNotifierProvider =
    StateNotifierProvider<ReportGenerationNotifier, ReportGenerationState>((ref) {
  final service = ref.watch(reportsServiceProvider);
  return ReportGenerationNotifier(service);
});

class ReportGenerationNotifier extends StateNotifier<ReportGenerationState>
    with WidgetsBindingObserver {
  final ReportsService _service;
  Timer? _pollingTimer;

  ReportGenerationNotifier(this._service) : super(const ReportGenerationState()) {
    WidgetsBinding.instance.addObserver(this);
  }

  @override
  void dispose() {
    WidgetsBinding.instance.removeObserver(this);
    _stopPolling();
    super.dispose();
  }

  @override
  void didChangeAppLifecycleState(AppLifecycleState appState) {
    if (appState == AppLifecycleState.paused) {
      _stopPolling();
    } else if (appState == AppLifecycleState.resumed) {
      if (state.activeReportId != null &&
          state.status != null &&
          state.status!.isProcessing) {
        startPolling(state.activeReportId!);
      }
    }
  }

  void _stopPolling() {
    _pollingTimer?.cancel();
    _pollingTimer = null;
    state = state.copyWith(isPolling: false);
  }

  Future<String?> createReportJob({
    required String birthProfileId,
    required String reportType,
    String? partnerProfileId,
    bool forceRegenerate = false,
  }) async {
    state = state.copyWith(
      isLoading: true,
      errorMessage: null,
      pdfBytes: forceRegenerate ? null : state.pdfBytes,
      status: forceRegenerate ? null : state.status,
    );

    try {
      final response = await _service.createReportJob(
        birthProfileId: birthProfileId,
        reportType: reportType,
        partnerProfileId: partnerProfileId,
        forceRegenerate: forceRegenerate,
        async: true,
      );

      final reportId = response['reportId'] as String? ?? response['id'] as String?;
      if (reportId == null) {
        state = state.copyWith(
          isLoading: false,
          errorMessage: 'Invalid response from report service.',
        );
        return null;
      }

      state = state.copyWith(
        isLoading: false,
        activeReportId: reportId,
        status: UserReportItemModel.fromJson(response),
      );

      startPolling(reportId);
      return reportId;
    } on AppException catch (e) {
      state = state.copyWith(isLoading: false, errorMessage: e.message);
      return null;
    } catch (e) {
      state = state.copyWith(
        isLoading: false,
        errorMessage: 'Unable to start report generation. Please try again.',
      );
      return null;
    }
  }

  void startPolling(String reportId) {
    _stopPolling();
    state = state.copyWith(isPolling: true, activeReportId: reportId);

    _poll(reportId);

    _pollingTimer = Timer.periodic(const Duration(milliseconds: 2500), (_) {
      _poll(reportId);
    });
  }

  void stopPolling() {
    _stopPolling();
  }


  Future<void> _poll(String reportId) async {
    try {
      final updatedStatus = await _service.getUniversalReportStatus(reportId);
      state = state.copyWith(status: updatedStatus);

      if (updatedStatus.isCompleted || updatedStatus.isFailed) {
        _stopPolling();
      }
    } catch (_) {
      // Continue polling silently on transient network blip
    }
  }

  Future<Uint8List?> downloadAndCachePdf(String reportId) async {
    if (state.activeReportId == reportId && state.pdfBytes != null) {
      return state.pdfBytes;
    }

    state = state.copyWith(isLoading: true, errorMessage: null);
    try {
      final bytes = await _service.downloadReportPdfBytes(reportId);
      state = state.copyWith(
        isLoading: false,
        pdfBytes: bytes,
        activeReportId: reportId,
      );
      return bytes;
    } on AppException catch (e) {
      state = state.copyWith(isLoading: false, errorMessage: e.message);
      return null;
    } catch (e) {
      state = state.copyWith(
        isLoading: false,
        errorMessage: 'Failed to download report PDF. Please try again.',
      );
      return null;
    }
  }
}

