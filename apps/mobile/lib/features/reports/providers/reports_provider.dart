class ReportGenerationState {
  final bool isLoading;
  final bool isPolling;
  final String? activeReportId;
  final UserReportItemModel? status;
  final Uint8List? pdfBytes;
  final String? errorMessage;

  const ReportGenerationState({
    this.isLoading = false,
    this.isPolling = false,
    this.activeReportId,
    this.status,
    this.pdfBytes,
    this.errorMessage,
  });

  ReportGenerationState copyWith({
    bool? isLoading,
    bool? isPolling,
    String? activeReportId,
    UserReportItemModel? status,
    Uint8List? pdfBytes,
    String? errorMessage,
  }) {
    return ReportGenerationState(
      isLoading: isLoading ?? this.isLoading,
