import 'package:flutter/foundation.dart';

/// Supported action types that Jyoti can suggest or perform.
enum JyotiActionType {
  openBirthChart,
  openPlanets,
  openHouses,
  openNakshatra,
  openRashiBhavishya,
  openVastu,
  openProfile,
  generateKundli,
}

extension JyotiActionTypeExtension on JyotiActionType {
  static JyotiActionType fromString(String typeStr) {
    final clean = typeStr.toUpperCase().replaceAll('JYOTIACTIONTYPE.', '');
    switch (clean) {
      case 'OPEN_BIRTH_CHART':
      case 'OPENBIRTHCHART':
      case 'GENERATEKUNDLI':
        return JyotiActionType.openBirthChart;
      case 'OPEN_PLANETS':
      case 'OPENPLANETS':
        return JyotiActionType.openPlanets;
      case 'OPEN_HOUSES':
      case 'OPENHOUSES':
        return JyotiActionType.openHouses;
      case 'OPEN_NAKSHATRA':
      case 'OPENNAKSHATRA':
        return JyotiActionType.openNakshatra;
      case 'OPEN_RASHI_BHAVISHYA':
      case 'OPENRASHIBHAVISHYA':
        return JyotiActionType.openRashiBhavishya;
      case 'OPEN_VASTU':
      case 'OPENVASTU':
        return JyotiActionType.openVastu;
      case 'OPEN_PROFILE':
      case 'OPENPROFILE':
        return JyotiActionType.openProfile;
      default:
        return JyotiActionType.openBirthChart;
    }
  }
}

/// Represents an actionable card payload generated by Jyoti.
@immutable
class JyotiAction {
  final JyotiActionType type;
  final String title;
  final String subtitle;
  final String buttonText;
  final Map<String, dynamic>? extraData;

  const JyotiAction({
    required this.type,
    required this.title,
    required this.subtitle,
    this.buttonText = 'Open Feature',
    this.extraData,
  });

  Map<String, dynamic> toJson() => {
        'type': type.name,
        'title': title,
        'subtitle': subtitle,
        'buttonText': buttonText,
        'extraData': extraData,
      };

  factory JyotiAction.fromJson(Map<String, dynamic> json) => JyotiAction(
        type: JyotiActionTypeExtension.fromString(json['type'] as String? ?? 'openBirthChart'),
        title: json['title'] as String? ?? 'Open Feature',
        subtitle: json['subtitle'] as String? ?? '',
        buttonText: json['buttonText'] as String? ?? 'Open Feature',
        extraData: json['extraData'] as Map<String, dynamic>?,
      );
}

/// Represents an expandable astrology topic explanation card.
@immutable
class JyotiExplanation {
  final String title;
  final String category;
  final String summary;
  final String detailedText;
  final String? actionButtonText;
  final JyotiActionType? actionType;

  const JyotiExplanation({
    required this.title,
    required this.category,
    required this.summary,
    required this.detailedText,
    this.actionButtonText,
    this.actionType,
  });

  Map<String, dynamic> toJson() => {
        'title': title,
        'category': category,
        'summary': summary,
        'detailedText': detailedText,
        'actionButtonText': actionButtonText,
        'actionType': actionType?.name,
      };

  factory JyotiExplanation.fromJson(Map<String, dynamic> json) => JyotiExplanation(
        title: json['title'] as String? ?? '',
        category: json['category'] as String? ?? 'Astrology',
        summary: json['summary'] as String? ?? '',
        detailedText: json['detailedText'] as String? ?? '',
        actionButtonText: json['actionButtonText'] as String?,
        actionType: json['actionType'] != null
            ? JyotiActionTypeExtension.fromString(json['actionType'] as String)
            : null,
      );
}

/// Category of message rendered in the chat view.
enum JyotiMessageType {
  user,
  jyotiText,
  actionCard,
  explanationCard,
  loading,
  error,
  offline,
}

/// Core model representing a single message in the Jyoti AI Assistant conversation.
@immutable
class JyotiMessageModel {
  final String id;
  final JyotiMessageType type;
  final String text;
  final DateTime timestamp;
  final JyotiAction? action;
  final JyotiExplanation? explanation;
  final bool isUser;

  const JyotiMessageModel({
    required this.id,
    required this.type,
    required this.text,
    required this.timestamp,
    this.action,
    this.explanation,
    this.isUser = false,
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'type': type.name,
        'text': text,
        'timestamp': timestamp.toIso8601String(),
        'action': action?.toJson(),
        'explanation': explanation?.toJson(),
        'isUser': isUser,
      };

  factory JyotiMessageModel.fromJson(Map<String, dynamic> json) => JyotiMessageModel(
        id: json['id'] as String? ?? DateTime.now().millisecondsSinceEpoch.toString(),
        type: JyotiMessageType.values.firstWhere(
          (e) => e.name == (json['type'] as String?),
          orElse: () => JyotiMessageType.jyotiText,
        ),
        text: json['text'] as String? ?? '',
        timestamp: DateTime.tryParse(json['timestamp'] as String? ?? '') ?? DateTime.now(),
        action: json['action'] != null ? JyotiAction.fromJson(json['action'] as Map<String, dynamic>) : null,
        explanation: json['explanation'] != null
            ? JyotiExplanation.fromJson(json['explanation'] as Map<String, dynamic>)
            : null,
        isUser: json['isUser'] as bool? ?? false,
      );

  factory JyotiMessageModel.user(String id, String text) {
    return JyotiMessageModel(
      id: id,
      type: JyotiMessageType.user,
      text: text,
      timestamp: DateTime.now(),
      isUser: true,
    );
  }

  factory JyotiMessageModel.jyotiText(String id, String text) {
    return JyotiMessageModel(
      id: id,
      type: JyotiMessageType.jyotiText,
      text: text,
      timestamp: DateTime.now(),
      isUser: false,
    );
  }

  factory JyotiMessageModel.action(String id, String text, JyotiAction action) {
    return JyotiMessageModel(
      id: id,
      type: JyotiMessageType.actionCard,
      text: text,
      action: action,
      timestamp: DateTime.now(),
      isUser: false,
    );
  }

  factory JyotiMessageModel.explanation(String id, String text, JyotiExplanation explanation) {
    return JyotiMessageModel(
      id: id,
      type: JyotiMessageType.explanationCard,
      text: text,
      explanation: explanation,
      timestamp: DateTime.now(),
      isUser: false,
    );
  }

  factory JyotiMessageModel.loading(String id) {
    return JyotiMessageModel(
      id: id,
      type: JyotiMessageType.loading,
      text: 'Jyoti is thinking...',
      timestamp: DateTime.now(),
      isUser: false,
    );
  }

  factory JyotiMessageModel.error(String id, {String? text}) {
    return JyotiMessageModel(
      id: id,
      type: JyotiMessageType.error,
      text: text ?? "Jyoti couldn't respond right now. Please try again.",
      timestamp: DateTime.now(),
      isUser: false,
    );
  }

  factory JyotiMessageModel.offline(String id) {
    return JyotiMessageModel(
      id: id,
      type: JyotiMessageType.offline,
      text: 'Jyoti needs an internet connection to answer new questions.',
      timestamp: DateTime.now(),
      isUser: false,
    );
  }
}
