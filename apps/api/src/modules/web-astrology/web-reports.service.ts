/**
 * The website's report purchase (`/report`, `/report/buy`, `/report/verify-payment`,
 * `/report/orders`) on this backend's own commerce and report platform.
 *
 * There is no second payment path and no second report generator here:
 *   - the order is placed by CommerceService.createOrder with the mapped catalogue item, so the
 *     price, GST and exchange rate are the server's (finding 3: nothing is taken from the request);
 *   - the payment is verified by CommerceService.verifyPayment (owner check, signature, amount and
 *     currency read back from the gateway), which raises `reportOrderConfirmed` through the
 *     notification bridge ("within the next 48 hours");
 *   - the report is created by ReportsService.createReportJob for the paid order, in the language
 *     stored on the order item, and generated by the existing worker; `reportReady` is raised for it
 *     REPORT_SEND_DELAY_HOURS after completion (reports/report-release.sweep.ts).
 * This module only translates the website's form into those calls and their results back.
 */

export interface WebsiteReportProduct {
  slug: string;
  reportType: WebsiteReportType;
  /** The website's product name. */
  name: string;
  /** Catalogue item that is sold for it (owner decision 2026-11-24). */
  catalogId: string;
  /** Report type the platform generates for it; must be the catalogue item's own type. */
  platformType: ReportType;
  /** Two people (bride and groom) instead of one. */
  couple: boolean;
  /** Lookup aliases (legacy slugs, legacy report types, retired catalog IDs/platform types). */
  aliases?: readonly string[];
  /** Legacy website reportType values accepted on buy() for this product. */
  legacyReportTypes?: readonly WebsiteReportType[];
  /** Default cover image path when no admin override exists. */
  defaultCoverImage?: string;
  /** Default SVG illustration path. */
  defaultIllustrationUrl?: string;
}

