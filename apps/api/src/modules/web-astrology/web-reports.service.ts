export interface WebReportsDeps {
  commerce?: Pick<typeof commerceService, 'createOrder' | 'verifyPayment'>;
  reports?: Pick<typeof reportsService, 'createReportJob' | 'getReportAccessUrl'>;
  profiles?: Pick<typeof birthProfilesService, 'createProfile'>;
  timezones?: PlaceTimezoneMemo;
  languagesOf?: (reportType: string) => string[];
  /** Delay between completion and release, in ms; default: the one rule of reports/report-release.ts. */
  releaseDelayMs?: () => number;
  now?: () => Date;
}

export class WebReportsService {
  private readonly commerce: Pick<typeof commerceService, 'createOrder' | 'verifyPayment'>;
  private readonly reports: Pick<typeof reportsService, 'createReportJob' | 'getReportAccessUrl'>;
  private readonly profiles: Pick<typeof birthProfilesService, 'createProfile'>;
  private readonly timezones: PlaceTimezoneMemo;
  private readonly languagesOf: (reportType: string) => string[];
  private readonly releaseDelayMs: () => number;
  private readonly now: () => Date;

  constructor(deps: WebReportsDeps = {}) {
    this.commerce = deps.commerce ?? commerceService;
    this.reports = deps.reports ?? reportsService;
    this.profiles = deps.profiles ?? birthProfilesService;
    this.timezones = deps.timezones ?? webAstrologyService.timezones;
    this.languagesOf = deps.languagesOf ?? platformReportLanguages;
    this.releaseDelayMs = deps.releaseDelayMs ?? (() => reportReleaseDelayMs());
    this.now = deps.now ?? (() => new Date());
  }

  // ---- products ----------------------------------------------------------------------------

  private resolve(product: WebsiteReportProduct): ResolvedProduct | null {
    const item = commerceCatalog.getItem(product.catalogId);
    if (!item || item.itemType !== OrderItemType.REPORT) return null;
    // The mapping is only valid while the catalogue item still is the report it names.
    if (item.legacyReportType !== product.platformType) return null;
    return { product, item, reportType: item.legacyReportType };
  }

  /** A product in the website's `Report` shape. Every amount comes from the catalogue item. */
  private toWebsiteReport({ product, item, reportType }: ResolvedProduct) {
    const availableForPurchase = item.isActive && item.pricePaise > 0;
    const effectivePricePaise = item.pricePaise > 0 ? item.pricePaise : 0;
    // The catalogue stores the amount the customer pays. The split is the money engine's own.
    const split = computeGst(effectivePricePaise, {
      enabled: item.taxRateBasisPoints > 0 && effectivePricePaise > 0,
      rateBp: item.taxRateBasisPoints,
      type: item.taxIncluded ? 'inclusive' : 'exclusive',
    });
    const ratePercent = effectivePricePaise > 0 ? item.taxRateBasisPoints / 100 : 0;
    // Admin edits (owner decision 2026-11-26: the website admin's report editor).
    const edit = reportCatalogOverrides.get(item.id);
    return {
      _id: item.id,
      name: edit?.name?.trim() || product.name,
      slug: this.slugOf(product),
      reportType: product.reportType,
      platformType: reportType,
      shortDescription: edit?.shortDescription?.trim() || item.description,
      description: item.description,
      // Shown as on the website: the price before GST, with GST added at checkout.
      originalPrice: item.originalPricePaise !== undefined ? paiseToRupees(item.originalPricePaise) : null,
      pricePaise: effectivePricePaise,
      salePrice: paiseToRupees(split.basePaise),
      gst: { enabled: item.taxRateBasisPoints > 0 && effectivePricePaise > 0, rate: ratePercent, type: 'exclusive' as const },
      priceWithGst: paiseToRupees(split.totalPaise),
      priceBreakdown: {
        rate: ratePercent,
        base: paiseToRupees(split.basePaise),
        taxAmount: paiseToRupees(split.taxPaise),
        total: paiseToRupees(split.totalPaise),
        type: 'exclusive' as const,
      },
      // The same amounts in paise, for clients that do not want decimals.
      salePricePaise: split.basePaise,
      gstPaise: split.taxPaise,
      priceWithGstPaise: split.totalPaise,
      currency: item.currency,
      languages: this.languagesOf(reportType),
      isActive: item.isActive,
      availableForPurchase,
      isPremium: edit?.isPremium ?? true,
      requires: product.couple ? 'matchMakingDetails' : 'customerDetails',
      // Brand assets default to the canonical report cover & spot illustration when no admin override exists.
      coverImage: edit?.coverImageUrl || product.defaultCoverImage || `/report-assets/covers/web-preview/${item.id}.webp`,
      illustrationUrl: product.defaultIllustrationUrl || `/report-assets/illustrations/reports/${item.id}.svg`,
      benefits: edit?.benefits ?? [],
      features: edit?.features ?? [],
      faqs: edit?.faqs ?? [],
    };
  }

  public listReports() {
    return WEBSITE_REPORT_PRODUCTS.map((p) => this.resolve(p))
      .filter((r): r is ResolvedProduct => r !== null)
      .map((r) => this.toWebsiteReport(r));
  }

  /** The product's slug: the one set in the admin, else the code one. */
  private slugOf(product: WebsiteReportProduct): string {
    return reportCatalogOverrides.get(product.catalogId)?.slug?.trim() || product.slug;
  }

  private matchesReference(product: WebsiteReportProduct, ref: string): boolean {
    return (
      this.slugOf(product).toLowerCase() === ref ||
      product.slug.toLowerCase() === ref ||
      product.catalogId.toLowerCase() === ref ||
      product.reportType.toLowerCase() === ref ||
      product.platformType.toLowerCase() === ref ||
      (product.aliases ?? []).some((alias) => alias.toLowerCase() === ref)
    );
  }

  private findProduct(reference: string): ResolvedProduct {
    const ref = reference.trim().toLowerCase();
    // Canonical products take precedence, then legacy products (`mini-horoscope`, `basic-horoscope`).
    const product = ALL_WEBSITE_REPORT_PRODUCTS.find((p) => this.matchesReference(p, ref));
    const resolved = product ? this.resolve(product) : null;
    if (!resolved) throw new NotFoundError('Report not found');
    return resolved;
  }

  public getReport(reference: string) {
    return this.toWebsiteReport(this.findProduct(reference));
  }

  // ---- birth profiles ----------------------------------------------------------------------

  /**
   * The buyer's birth profile for one person of the form: an existing profile of this user with the
   * same name, date, time, coordinates and timezone is reused, otherwise one is created through
   * BirthProfilesService (which resolves the birth instant, including daylight-saving cases).
   */
  private async findOrCreateProfile(userId: string, person: WebPersonInput, field: string): Promise<string> {
    const tz = await resolveBirthTimezone(this.timezones, person, `${field}.timezone`);
    const existing = await prisma.birthProfile.findMany({ where: { userId } });
    const name = person.fullName.trim().toLowerCase();
    const same = existing.find(
      (p) =>
        p.name.trim().toLowerCase() === name &&
        p.dateOfBirth === person.dateOfBirth &&
        (p.timeOfBirth.length === 5 ? `${p.timeOfBirth}:00` : p.timeOfBirth) === person.timeOfBirth &&
        Math.abs(p.latitude - person.latitude) < 0.0001 &&
        Math.abs(p.longitude - person.longitude) < 0.0001 &&
        p.timezone === tz.timezone
    );
    const gender = person.gender ? (String(person.gender).toLowerCase() as 'male' | 'female' | 'other') : undefined;
    if (same) {
      if (!same.gender && gender) await prisma.birthProfile.update({ where: { id: same.id }, data: { gender } });
      return same.id;
    }
    const created = await this.profiles.createProfile(userId, {
      ...(gender && ['male', 'female', 'other'].includes(gender) ? { gender } : {}),
      name: person.fullName,
      dateOfBirth: person.dateOfBirth,
      timeOfBirth: person.timeOfBirth,
      latitude: person.latitude,
      longitude: person.longitude,
      timezone: tz.timezone,
      placeName: person.birthPlace,
    });
    return created.id;
  }

  private contactOf(person: WebPersonInput) {
    return {
      fullName: person.fullName,
      email: person.email,
      whatsappNumber: person.whatsappNumber,
      pinCode: person.pinCode,
      gender: person.gender,
    };
  }

  // ---- buy ---------------------------------------------------------------------------------

  public async buy(input: WebBuyReportInput, user: UserContext) {
    const resolved = this.findProduct(input.reportId);
    const { product, item, reportType } = resolved;

    if (!item.isActive || item.pricePaise <= 0) {
      throw new ValidationError(`Offering "${item.title}" is currently unavailable for purchase`, [
        { field: 'reportId', message: 'This report is not yet available for purchase' },
      ]);
    }

    // The type is the product's (or its preserved legacy alias). A request naming another type for this product is refused.
    const allowedTypes = new Set<string>([product.reportType, ...(product.legacyReportTypes ?? [])]);
    if (input.reportType && !allowedTypes.has(input.reportType)) {
      throw new ValidationError('reportType does not match the selected report', [
        { field: 'reportType', message: `This report is "${product.reportType}"` },
      ]);
    }

    let language: 'en' | 'hi';
    if (product.couple) {
      if (!input.matchMakingDetails) {
        throw new ValidationError('Bride and groom details are required for this report', [{ field: 'matchMakingDetails', message: 'Required' }]);
      }
      language = input.matchMakingDetails.reportLanguage;
    } else {
      if (!input.customerDetails) {
        throw new ValidationError('Customer details are required for this report', [{ field: 'customerDetails', message: 'Required' }]);
      }
      language = input.customerDetails.reportLanguage;
    }

    // Checked before a profile or an order is created (the commerce layer checks it again before charging).
    const available = this.languagesOf(reportType);
    if (!available.includes(language)) {
      throw new AppError(
        `The ${product.name} report is not available in language "${language}". Available: ${available.join(', ') || 'none'}.`,
        400,
        'REPORT_LANGUAGE_NOT_AVAILABLE'
      );
    }

    let metadata: WebReportItemMetadata;
    if (product.couple && input.matchMakingDetails) {
      const { bride, groom } = input.matchMakingDetails;
      // The couple report counts the primary profile as the groom's chart in the directional
      // kootas, so the groom is the primary profile and the bride the partner profile.
      const groomProfileId = await this.findOrCreateProfile(user.id, groom, 'matchMakingDetails.groom');
      const brideProfileId = await this.findOrCreateProfile(user.id, bride, 'matchMakingDetails.bride');
      if (groomProfileId === brideProfileId) {
        throw new ValidationError('Bride and groom details must be two different people', [{ field: 'matchMakingDetails', message: 'Identical birth details' }]);
      }
      metadata = {
        source: 'website',
        websiteReportType: product.reportType,
        birthProfileId: groomProfileId,
        partnerProfileId: brideProfileId,
        language,
        contact: this.contactOf(groom),
        partnerContact: this.contactOf(bride),
      };
    } else {
      const person = input.customerDetails as NonNullable<WebBuyReportInput['customerDetails']>;
      metadata = {
        source: 'website',
        websiteReportType: product.reportType,
        birthProfileId: await this.findOrCreateProfile(user.id, person, 'customerDetails'),
        language,
        contact: this.contactOf(person),
      };
    }

    // Price, GST and exchange rate are worked out by the commerce layer from the catalogue item.
    const order = await this.commerce.createOrder(
      {
        items: [{ catalogId: item.id, quantity: 1, metadata: { ...metadata } }],
        currency: input.currency,
        idempotencyKey: input.idempotencyKey,
        ...(input.couponCode ? { couponCode: input.couponCode } : {}),
      },
      user
    );

    logger.info({ userId: user.id, orderId: order.orderId, catalogId: item.id, language }, '[web-reports] Report order created');

    return {
      order: {
        _id: order.orderId,
        reportId: item.id,
        reportType: product.reportType,
        reportLanguage: language,
        // INR amount of the order in rupees; `amountPaise` is the same in paise.
        baseAmount: paiseToRupees(order.amount),
        amountPaise: order.amount,
        currency: order.paidCurrency || order.currency,
        razorpayOrderId: order.razorpayOrderId,
        paymentStatus: 'pending',
        reportStatus: 'pending',
      },
      razorpayConfig: {
        key: order.razorpayKey,
        orderId: order.razorpayOrderId,
        // Minor units of the charged currency, as the checkout widget expects.
        amount: order.paidAmountMinor,
        currency: order.paidCurrency || order.currency,
      },
    };
  }

  // ---- verify + report creation ------------------------------------------------------------

  public async verifyPayment(input: WebVerifyReportPaymentInput, user: UserContext) {
    const verified = await this.commerce.verifyPayment(
      {
        razorpayOrderId: input.razorpay_order_id,
        razorpayPaymentId: input.razorpay_payment_id,
        razorpaySignature: input.razorpay_signature,
      },
      user
    );
    const orderId: string = verified.order.id;

    // The payment stands whatever happens next. If the report job cannot be created now, the
    // order stays paid and this call (or ensureReportForOrder) can be repeated: both are idempotent.
    let generation: 'pending' | 'processing' | 'completed' = 'pending';
    try {
      const ensured = await this.ensureReportForOrder(orderId, user);
      if (ensured.created.length > 0 || ensured.existing.length > 0) generation = 'processing';
      if (ensured.completed) generation = 'completed';
    } catch (err) {
      logger.error(
        { orderId, userId: user.id, err: err instanceof Error ? err.message : String(err) },
        '[web-reports] Payment verified but the report job could not be created; it remains pending'
      );
    }

    return {
      _id: orderId,
      paymentStatus: 'paid',
      // As on the website: the report is delivered later, never at payment.
      reportStatus: 'pending',
      reportGenerationStatus: generation,
      isReportSent: false,
      deliveryMessage: 'Your report will be delivered within 48 hours.',
    };
  }

  /**
   * Creates the report(s) of a paid website report order through ReportsService, in the language
   * bought. Idempotent: ReportsService returns the report already bound to the paid slot.
   * Orders that did not come from the website form (no birth profile on the item) are left alone.
   */
  public async ensureReportForOrder(
    orderId: string,
    user: UserContext
  ): Promise<{ created: string[]; existing: string[]; completed: boolean }> {
    const order = await prisma.order.findFirst({ where: { id: orderId, userId: user.id }, include: { items: true } });
    if (!order) throw new NotFoundError('Order not found');
    // A fulfilled order already has its report; ReportsService only binds reports to PAID orders.
    if (order.status === OrderStatus.FULFILLED) return { created: [], existing: [], completed: true };
    if (order.status !== OrderStatus.PAID) {
      throw new AppError('The order is not paid', 409, 'ORDER_NOT_PAID');
    }

    const created: string[] = [];
    const existing: string[] = [];
    let completed = false;
    for (const orderItem of order.items) {
      if (orderItem.itemType !== OrderItemType.REPORT) continue;
      const meta = (orderItem.metadata ?? null) as Partial<WebReportItemMetadata> | null;
      if (!meta || meta.source !== 'website' || typeof meta.birthProfileId !== 'string') continue;
      const product = ALL_WEBSITE_REPORT_PRODUCTS.find((p) => p.catalogId === orderItem.catalogId);
      const catalogItem = commerceCatalog.getItem(orderItem.catalogId);
      const reportType =
        product && catalogItem?.legacyReportType === product.platformType
          ? product.platformType
          : orderItem.catalogId === 'report-career-pro' && catalogItem?.legacyReportType === 'CAREER_PROSITY'
            ? 'CAREER_PROSITY'
            : null;
      if (!reportType) continue;
      const job = await this.reports.createReportJob(
        {
          birthProfileId: meta.birthProfileId,
          partnerProfileId: typeof meta.partnerProfileId === 'string' ? meta.partnerProfileId : undefined,
          reportType: reportType as CreateReportInput['reportType'],
          orderId: order.id,
          // The language bought. ReportsService refuses any other language for this paid slot.
          language: meta.language === 'hi' ? 'hi' : 'en',
        },
        user
      );
      const reportId: string | undefined = job?.reportId ?? job?.id;
      if (reportId) (job?.reused ? existing : created).push(reportId);
      if (job?.status === 'COMPLETED') completed = true;
    }
    return { created, existing, completed };
  }

  // ---- delivered orders --------------------------------------------------------------------

  /**
   * The buyer's report orders in the website's `ReportOrder` shape. As on the website
   * (`reportStatus: "completed", isReportSent: true`), an order appears only once its report has
   * been released to the customer: completed, and the delivery delay (REPORT_SEND_DELAY_HOURS) has
   * passed. "Released" is decided by reports/report-release.ts, the same rule the report API and the
   * release announcement use.
   * `reportUrl` is a short-lived signed link (the website's links were permanent public files).
   */
  public async listDeliveredOrders(user: UserContext) {
    const delayMs = this.releaseDelayMs();
    const now = this.now();
    const reports = await prisma.report.findMany({
      where: { userId: user.id, orderId: { not: null }, status: 'COMPLETED' },
      include: { order: { include: { items: true } } },
      orderBy: { completedAt: 'desc' },
    });

    const rows: WebsiteReportOrderRow[] = [];
    for (const report of reports) {
      const order = report.order;
      if (!order || order.userId !== user.id) continue;
      if (order.status === OrderStatus.REFUNDED || order.status === OrderStatus.CANCELLED || order.status === OrderStatus.PENDING || order.status === OrderStatus.FAILED) continue;
      if (!isReportReleased(report, now, delayMs)) continue;
      const releasedAt = reportAvailableAt(report, delayMs);

      const catalogItem = commerceCatalog.getItemByLegacyReportType(report.reportType);
      const orderItem = order.items.find((i) => i.itemType === OrderItemType.REPORT && (!catalogItem || i.catalogId === catalogItem.id)) ?? null;
      const resolvedCatalogId = orderItem?.catalogId ?? catalogItem?.id;
      const product =
        ALL_WEBSITE_REPORT_PRODUCTS.find((p) => p.catalogId === resolvedCatalogId) ??
        (resolvedCatalogId === 'report-career-pro'
          ? WEBSITE_REPORT_PRODUCTS.find((p) => p.catalogId === 'report-career')
          : undefined);

      let reportUrl: string | null = null;
      try {
        reportUrl = (await this.reports.getReportAccessUrl(report.id, user)).accessUrl;
      } catch (err) {
        logger.warn({ reportId: report.id, err: err instanceof Error ? err.message : String(err) }, '[web-reports] No download link for a delivered report');
      }

      rows.push({
        _id: order.id,
        reportDbId: report.id,
        reportId: {
          _id: orderItem?.catalogId ?? catalogItem?.id ?? null,
          name: product?.name ?? orderItem?.title ?? catalogItem?.title ?? 'Astrology Report',
          slug: product?.slug ?? null,
          reportType: product?.reportType ?? null,
        },
        reportType: product?.reportType ?? null,
        reportLanguage: report.language,
        reportUrl,
        reportStatus: 'completed',
        isReportSent: true,
        paymentStatus: 'paid',
        baseAmount: paiseToRupees(order.amount),
        amountPaise: order.amount,
        currency: order.currency,
        createdAt: order.createdAt,
        // Null for a report completed before completion times were recorded.
        deliveredAt: releasedAt && releasedAt.getTime() > 0 ? releasedAt : null,
      });
    }
    return rows;
  }
}

