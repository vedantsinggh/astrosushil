import { JyotiActionPayload } from '../providers/llm.provider';

export enum AllowedJyotiAction {
  OPEN_HOME = 'OPEN_HOME',
  OPEN_BIRTH_CHART = 'OPEN_BIRTH_CHART',
  OPEN_PLANETS = 'OPEN_PLANETS',
  OPEN_HOUSES = 'OPEN_HOUSES',
  OPEN_NAKSHATRA = 'OPEN_NAKSHATRA',
  OPEN_RASHI_BHAVISHYA = 'OPEN_RASHI_BHAVISHYA',
  OPEN_VASTU = 'OPEN_VASTU',
  OPEN_PROFILE = 'OPEN_PROFILE',
  OPEN_SETTINGS = 'OPEN_SETTINGS',
  OPEN_REPORTS = 'OPEN_REPORTS',
  OPEN_CAREER_REPORT = 'OPEN_CAREER_REPORT',
  GENERATE_CAREER_REPORT = 'GENERATE_CAREER_REPORT',
  OPEN_SUBSCRIPTION = 'OPEN_SUBSCRIPTION',
  OPEN_PAYMENT = 'OPEN_PAYMENT',
  OPEN_NOTIFICATIONS = 'OPEN_NOTIFICATIONS',
  OPEN_NOTIFICATION_SETTINGS = 'OPEN_NOTIFICATION_SETTINGS',
  OPEN_ACCOUNT = 'OPEN_ACCOUNT',
  OPEN_BIRTH_PROFILE = 'OPEN_BIRTH_PROFILE',
  OPEN_JYOTI = 'OPEN_JYOTI',
  OPEN_HELP = 'OPEN_HELP',
  OPEN_ABOUT = 'OPEN_ABOUT',
  OPEN_LOGIN = 'OPEN_LOGIN',
  CONFIRM_LOGOUT = 'CONFIRM_LOGOUT',
}

export class ActionRegistry {
  private static readonly ALLOWED_SET = new Set<string>(Object.values(AllowedJyotiAction));

  /**
   * Returns true if the action type is in the security allowlist.
   */
  public static isActionAllowed(actionType: string): boolean {
    return this.ALLOWED_SET.has(actionType.toUpperCase());
  }

  /**
   * Filters and validates action payloads generated by LLM, discarding dangerous or unauthorized action types.
   */
  public static validateActions(actions?: JyotiActionPayload[]): JyotiActionPayload[] {
    if (!actions || !Array.isArray(actions)) {
      return [];
    }

    return actions
      .filter((action) => action && typeof action.type === 'string' && this.isActionAllowed(action.type))
      .map((action) => ({
        type: action.type.toUpperCase(),
        title: action.title,
        subtitle: action.subtitle,
        buttonText: action.buttonText,
        parameters: action.parameters,
      }));
  }
}

