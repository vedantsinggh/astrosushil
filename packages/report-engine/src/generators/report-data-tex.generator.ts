/**
 * Escapes special LaTeX characters in user or dynamic text.
 * Contract: %, &, #, _, {, }, $, ~, ^, \ -> \%, \&, \#, \_, \{, \}, \$, \textasciitilde{}, \textasciicircum{}, \textbackslash{}
 * Preserves \textdegree{} and mathematical macros if already present.
 */
export function escapeLatex(text: string): string {
  if (!text) return '';

  const degreePlaceholder = 'DEGREEPLACEHOLDER';
  const backslashPlaceholder = 'BACKSLASHPLACEHOLDER';

  let clean = text;

  clean = clean.replace(/\\textdegree\{\}/g, degreePlaceholder);
  clean = clean.replace(/°/g, degreePlaceholder);
  clean = clean.replace(/\\/g, backslashPlaceholder);

  clean = clean
    .replace(/%/g, '\\%')
    .replace(/&/g, '\\&')
    .replace(/#/g, '\\#')
    .replace(/_/g, '\\_')
    .replace(/\{/g, '\\{')
    .replace(/\}/g, '\\}')
    .replace(/\$/g, '\\$')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}');

  clean = clean.replace(new RegExp(backslashPlaceholder, 'g'), () => '\\textbackslash{}');
  clean = clean.replace(new RegExp(degreePlaceholder, 'g'), () => '\\textdegree{}');
  return clean;
}

function renderValue(text: string, status: DataStatus): string {
  const escaped = escapeLatex(text);
  if (status === 'VERIFIED') {
    return `\\RenderVerified{${escaped}}`;
  }
  if (status === 'DERIVED') {
    return `\\RenderDerived{${escaped}}`;
  }
  return `\\RenderUnavailable{${escaped}}`;
}

function renderStatus(status: DataStatus): string {
  if (status === 'VERIFIED') return '\\VerifiedStatus';
  if (status === 'DERIVED') return '\\DerivedStatus';
  return '\\UnavailableStatus';
}

function renderCmd(cmdName: string, value: string): string {
  return `\\newcommand{\\${cmdName}}{${value}}\n`;
}

function renderValCmd(cmdName: string, text: string | number | undefined, status: DataStatus = 'VERIFIED'): string {
  const str = text !== undefined && text !== null ? String(text) : '';
  return renderCmd(cmdName, renderValue(str, status));
}

function renderStatusCmd(cmdName: string, status: DataStatus): string {
  return renderCmd(cmdName, renderStatus(status));
}

function getStatusForText(text: string | undefined, defaultStatus: DataStatus = 'VERIFIED'): DataStatus {
  if (
    !text ||
    text.trim() === '' ||
    text.includes('Personalized interpretation unavailable') ||
    text === 'Unavailable' ||
    text === 'Not supplied' ||
    text === 'Not calculated'
  ) {
    return 'UNAVAILABLE';
  }
  return defaultStatus;
}

