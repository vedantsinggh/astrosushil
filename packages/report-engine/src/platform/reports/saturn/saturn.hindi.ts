/** A fixed label of the Saturn blocks in the report language. An untranslated Hindi label is a defect, never printed as English. */
export function sl(lang: ReportLanguage, en: string): string {
  if (lang === 'en') return en;
  const hi = SATURN_LABELS_HI[en];
  if (hi === undefined) throw new Error(`HINDI_LABEL_MISSING: saturn "${en}"`);
  return pick(lang, en, hi);
}

