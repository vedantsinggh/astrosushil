#!/usr/bin/env bash
# =============================================================================
# render-proxy-access.sh - render the testing proxy access include files from
# $TESTING_ROOT/env/proxy.env.
#
# Usage:
#   infrastructure/testing/scripts/render-proxy-access.sh [--reload] [--check]
#
# Options:
#   --reload    after rendering, run `nginx -t` and `nginx -s reload` inside the
#               running testing-proxy container (skipped when it is not running)
#   --check     render to a temporary directory and print the result only
#   -h, --help  show this help
#
# Writes (atomically, mode 644, no secrets; directory $TESTING_ROOT/nginx, 755).
# All three files are always written (comment-only when nothing applies),
# because testing.conf includes them unconditionally:
#   access-website.conf  access-admin.conf  access-api.conf
# Each file holds only directives valid in nginx `server` context:
#   set_real_ip_from <cidr>; real_ip_header X-Forwarded-For; real_ip_recursive on;
#       for every TESTING_TRUSTED_PROXY_CIDRS entry (host proxy addresses)
#   allow <cidr>; ... deny all;     when TESTING_ALLOWED_CIDRS is not empty
#   auth_basic "Astro Sushil testing"; auth_basic_user_file /etc/nginx/testing/htpasswd;
#       website + admin only, when TESTING_BASIC_AUTH_ENABLED=true (never api:
#       the mobile app cannot send basic auth)
# Invalid CIDRs abort the run before any file is written.
#
# Touches only $TESTING_ROOT/nginx and (with --reload) the astro_testing proxy
# container. Never edits host Caddy/Nginx or firewall rules.
# Exit codes: 0 ok, 1 error.
# =============================================================================
set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"

RELOAD=0; CHECK=0
while (($#)); do
  case "$1" in
    --reload) RELOAD=1; shift ;;
    --check) CHECK=1; shift ;;
    -h|--help) print_script_help "$0"; exit 0 ;;
    *) die "Unknown option: $1 (see --help)" ;;
  esac
done

PROXY_ENV="$TESTING_ENV_DIR/proxy.env"
[[ -f "$PROXY_ENV" ]] || die "Missing $PROXY_ENV (run install-testing.sh first)."

BASIC_AUTH="$(env_file_get "$PROXY_ENV" TESTING_BASIC_AUTH_ENABLED || true)"; BASIC_AUTH="${BASIC_AUTH:-true}"
ALLOWED="$(env_file_get "$PROXY_ENV" TESTING_ALLOWED_CIDRS || true)"
TRUSTED="$(env_file_get "$PROXY_ENV" TESTING_TRUSTED_PROXY_CIDRS || true)"
case "${BASIC_AUTH,,}" in
  true|1|yes) BASIC_AUTH=true ;;
  false|0|no) BASIC_AUTH=false ;;
  *) die "TESTING_BASIC_AUTH_ENABLED must be true or false (got '$BASIC_AUTH')." ;;
esac

IPV4_RE='^((25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])\.){3}(25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])(/(3[0-2]|[12]?[0-9]))?$'
IPV6_RE='^[0-9A-Fa-f:]*:[0-9A-Fa-f:.]*(/(12[0-8]|1[01][0-9]|[1-9]?[0-9]))?$'
valid_cidr() {
  local c="$1"
  [[ "$c" =~ $IPV4_RE ]] && return 0
  if [[ "$c" =~ $IPV6_RE ]]; then
    local addr="${c%%/*}"
    # At most one "::" and at most 8 groups.
    [[ "$addr" != *":::"* ]] || return 1
    local dbl="${addr//[^:]}"; (( ${#dbl} <= 7 )) || return 1
    local rest="${addr#*::}"; [[ "$rest" != *"::"* ]] || return 1
    return 0
  fi
  return 1
}

# split_list "<comma/space list>" -> one validated entry per line
split_list() {
  local name="$1" list="$2" item
  local IFS=$', \t'
  for item in $list; do
    [[ -z "$item" ]] && continue
    valid_cidr "$item" || die "$name: invalid IPv4/IPv6 address or CIDR '$item'."
    printf '%s\n' "$item"
  done
}

# Validate first in this shell (a failing process substitution would not stop mapfile).
split_list TESTING_ALLOWED_CIDRS "$ALLOWED" >/dev/null
split_list TESTING_TRUSTED_PROXY_CIDRS "$TRUSTED" >/dev/null
mapfile -t ALLOWED_LIST < <(split_list TESTING_ALLOWED_CIDRS "$ALLOWED")
mapfile -t TRUSTED_LIST < <(split_list TESTING_TRUSTED_PROXY_CIDRS "$TRUSTED")

render() {
  local origin="$1" c
  printf '# Generated by render-proxy-access.sh from env/proxy.env on %s. Do not edit;\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf '# change proxy.env and re-run the script. Origin: %s (server context only).\n' "$origin"
  if (( ${#TRUSTED_LIST[@]} > 0 )); then
    for c in "${TRUSTED_LIST[@]}"; do printf 'set_real_ip_from %s;\n' "$c"; done
    printf 'real_ip_header X-Forwarded-For;\nreal_ip_recursive on;\n'
  fi
  if (( ${#ALLOWED_LIST[@]} > 0 )); then
    # Loopback stays allowed so container health checks (run inside the
    # proxy container on 127.0.0.1) keep working. Requests from the host
    # (host proxy, verify-testing.sh) arrive from the Docker network gateway:
    # add that address to TESTING_ALLOWED_CIDRS or TESTING_TRUSTED_PROXY_CIDRS.
    printf 'allow 127.0.0.1;\nallow ::1;\n'
    for c in "${ALLOWED_LIST[@]}"; do printf 'allow %s;\n' "$c"; done
    printf 'deny all;\n'
  fi
  if [[ "$origin" != "api" && "$BASIC_AUTH" == "true" ]]; then
    printf 'auth_basic "Astro Sushil testing";\nauth_basic_user_file /etc/nginx/testing/htpasswd;\n'
  fi
}

if (( CHECK == 1 )); then
  for o in website admin api; do printf '### access-%s.conf\n' "$o"; render "$o"; done
  exit 0
fi

ensure_dir "$TESTING_NGINX_DIR" 755
if [[ "$BASIC_AUTH" == "true" && ! -s "$TESTING_NGINX_DIR/htpasswd" ]]; then
  log_warn "Basic auth is enabled but $TESTING_NGINX_DIR/htpasswd is missing; install-testing.sh generates it."
fi
for o in website admin api; do
  render "$o" | write_file_atomic "$TESTING_NGINX_DIR/access-$o.conf" 644
done
# nginx workers inside the container run as uid 101 and read htpasswd per request;
# the master (root) reads the include files. Keep group 101 when we can set it.
# Keep htpasswd readable for that uid: 640 with group 101 as root, else 644.
if [[ -f "$TESTING_NGINX_DIR/htpasswd" ]]; then
  if [[ "$(id -u)" -eq 0 ]]; then
    chgrp 101 "$TESTING_NGINX_DIR/htpasswd" && chmod 640 "$TESTING_NGINX_DIR/htpasswd"
  else
    chmod 644 "$TESTING_NGINX_DIR/htpasswd"
  fi
fi
log_ok "Rendered access-website.conf, access-admin.conf, access-api.conf in $TESTING_NGINX_DIR (basic auth: $BASIC_AUTH, allowlist entries: ${#ALLOWED_LIST[@]}, trusted proxies: ${#TRUSTED_LIST[@]})"

if (( RELOAD == 1 )); then
  if [[ -n "$(testing_container_id testing-proxy)" ]]; then
    assert_testing_container testing-proxy
    testing_compose exec -T testing-proxy nginx -t || die "nginx -t failed; the running proxy keeps its previous config."
    testing_compose exec -T testing-proxy nginx -s reload
    log_ok "testing-proxy reloaded"
  else
    log_info "testing-proxy is not running; the files are used on next start."
  fi
fi
